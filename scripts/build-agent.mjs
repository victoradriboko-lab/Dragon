import { build } from 'esbuild';
import { mkdirSync,writeFileSync,copyFileSync,existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve,join } from 'node:path';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
if(process.platform!=='win32')throw Error('Gere o executável Windows em Windows ou no workflow build-agent.');
mkdirSync('build/payload',{recursive:true});
await build({entryPoints:['agents/executable-entry.mjs'],bundle:true,platform:'node',target:'node24',format:'cjs',outfile:'build/agent.cjs',define:{'import.meta.url':'undefined'}});
writeFileSync('build/sea-config.json',JSON.stringify({main:'build/agent.cjs',output:'build/sea.blob',disableExperimentalSEAWarning:true,useSnapshot:false,useCodeCache:false,execArgvExtension:'none'}));
execFileSync(process.execPath,['--experimental-sea-config','build/sea-config.json'],{stdio:'inherit'});
const exe=resolve('build/payload/DragonAgent.exe');copyFileSync(process.execPath,exe);
const tools=execFileSync('powershell.exe',['-NoProfile','-Command',"Get-ChildItem (Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\\10\\bin\\*\\x64\\signtool.exe') -ErrorAction SilentlyContinue | Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName"],{encoding:'utf8'}).trim();
if(tools&&existsSync(tools))execFileSync(tools,['remove','/s',exe],{stdio:'inherit'});
const postject=join(require.resolve('postject/package.json'),'..','dist','cli.js');
execFileSync(process.execPath,[postject,exe,'NODE_SEA_BLOB',resolve('build/sea.blob'),'--sentinel-fuse','NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2'],{stdio:'inherit'});
const version=execFileSync(exe,['--version'],{encoding:'utf8'}).trim();
if(!version.startsWith('Dragon Agent '))throw Error('O executável não passou no teste de inicialização.');
console.log(version);
